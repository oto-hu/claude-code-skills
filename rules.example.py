"""置換ルールのひな形。`rules.py` にコピーして、自分の値に書き換えて使う。

**rules.py は絶対に公開しない。** 実名とプレースホルダの対応表そのものなので、
公開するとサニタイズが逆引きできてしまう。`.gitignore` に入れておくこと。

書き方のコツ：
- 上から順に適用される。**メールアドレスなど、広くマッチするものを先に潰す**
- すでに置換済みのプレースホルダを後続ルールが再置換しないよう、否定先読みを入れる
- 長い表記から短い表記の順に並べる（「山田太郎」→「山田」の順）
- 置換の結果おかしくなった表記を直すルールは、必ず最後に置く
"""

import re

RULES: list[tuple[str, str, str]] = [
    # (説明, 正規表現, 置換後)

    # --- ID・アドレス系（先に潰す） ---
    ("カレンダーID(仕事)",
     r"あなたのカレンダーIDの先頭[0-9a-f]+@group\.calendar\.google\.com",
     "work-calendar-id@group.calendar.google.com"),
    ("メールアドレス",
     r"[A-Za-z0-9._%+-]+@(?!example\.com|group\.calendar\.google\.com)"
     r"[A-Za-z0-9.-]+\.[A-Za-z]{2,}",
     "you@example.com"),
    ("Notion ID(UUID形式)",
     r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b",
     "00000000-0000-0000-0000-000000000000"),
    ("Notion ID(32桁)", r"\b[0-9a-f]{32}\b", "0" * 32),
    ("GA4プロパティID", r"\bあなたのプロパティID\b", "000000000"),

    # --- 組織・人名（自分の環境に合わせて書き換える） ---
    ("勤務先", r"勤務先の社名|SHAMEI|shamei", "本業"),
    ("取引先1", r"取引先Aの社名", "業務委託先A"),
    ("取引先2", r"取引先Bの社名", "顧問先B"),
    ("氏名(ローマ字)", r"Taro Yamada|Yamada|yamada", "You"),
    ("氏名(漢字)", r"山田太郎|太郎", "著者"),
    ("関係者の実名", r"関係者の名字", "担当者"),
    ("サンプルデータの氏名", r"サンプルに入っている実名", "サンプル太郎"),

    # --- パス ---
    ("ホームディレクトリ", r"/Users/yourname", "/Users/you"),

    # --- 置換の結果おかしくなった表記を整える（必ず最後） ---
    ("重複置換の整形", r"本業（本業）|本業\(本業\)", "本業"),
]

# 置換後にこれが残っていたら失敗とみなす。
# 置換ルールとは独立に書く——置換したことと、漏れがないことは別だから。
# 自分が置いたプレースホルダを弾かないよう、否定先読みで除外する。
FORBIDDEN = re.compile(
    r"勤務先の社名|取引先Aの社名|取引先Bの社名|Yamada|yamada|山田|太郎|"
    r"\b(?!0{32})[0-9a-f]{32}\b|"
    r"@group\.calendar\.google\.com(?<!work-calendar-id@group\.calendar\.google\.com)"
)
